# HISTORICAL DATA GENERATOR
# ============================================================


def generate_default_historical_data(
    database_path: Path,
    sample_csv_path: Path,
    days: int = 7,
    seed: int = 42,
) -> HistoricalGenerationSummary:
    """
    Generate historical telemetry and save a CSV sample.
    """

    if days <= 0:
        raise ValueError(
            "days must be positive"
        )

    engine = SimulationEngine(
        preset_name="airport",
        database_path=database_path,
        start_time=datetime(
            2026,
            1,
            1,
            0,
            0,
            tzinfo=timezone.utc,
        ),
        tick_minutes=1,
        live_tick_seconds=0,
        seed=seed,
    )

    total_minutes = days * 24 * 60

    results = []

    for _ in range(
        total_minutes
    ):
        results.append(
            engine.run_tick(
                persist=True
            )
        )

    # ------------------------------------------------------------
    # Flatten readings
    # ------------------------------------------------------------

    all_readings: list[
        SensorReading
    ] = []

    for result in results:
        all_readings.extend(
            result.readings
        )

    # ------------------------------------------------------------
    # Write CSV
    # ------------------------------------------------------------

    sample_csv_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    with sample_csv_path.open(
        "w",
        newline="",
        encoding="utf-8",
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=[
                "sensor_id",
                "fixture_id",
                "zone_id",
                "facility_id",
                "timestamp",
                "sensor_type",
                "value",
                "unit",
                "diagnostic_status",
                "quality_flag",
                "metadata",
            ],
        )

        writer.writeheader()

        for reading in all_readings:

            writer.writerow(
                {
                    "sensor_id": (
                        reading.sensor_id
                    ),
                    "fixture_id": (
                        reading.fixture_id
                    ),
                    "zone_id": (
                        reading.zone_id
                    ),
                    "facility_id": (
                        reading.facility_id
                    ),
                    "timestamp": (
                        reading.timestamp.isoformat()
                    ),
                    "sensor_type": (
                        reading.sensor_type
                    ),
                    "value": (
                        reading.value
                    ),
                    "unit": (
                        reading.unit
                    ),
                    "diagnostic_status": (
                        reading.diagnostic_status
                    ),
                    "quality_flag": (
                        reading.quality_flag
                    ),
                    "metadata": (
                        reading.metadata
                    ),
                }
            )

    return HistoricalGenerationSummary(
        total_readings=len(
            all_readings
        ),
        sample_readings=all_readings[
            :10
        ],
        database_path=database_path,
        sample_csv_path=sample_csv_path,
    )


