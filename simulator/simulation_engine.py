def main() -> None:
    """CLI entry point."""

    parser = _build_cli_parser()

    args = parser.parse_args()

    settings = get_settings()

    # ========================================================
    # HISTORICAL
    # ========================================================

    if args.command == "historical":

        summary = (
            generate_default_historical_data(
                database_path=(
                    settings.database_path
                ),
                sample_csv_path=(
                    settings.sample_csv_path
                ),
                days=args.days,
                seed=args.seed,
            )
        )

        print(
            f"Generated "
            f"{summary.total_readings} readings "
            f"into "
            f"{summary.database_path} "
            f"and "
            f"{summary.sample_csv_path}"
        )

        return

    # ========================================================
    # DEMO
    # ========================================================

    if args.command == "demo":

        engine = SimulationEngine(
            preset_name=args.facility,
            database_path=(
                settings.database_path
            ),
            start_time=datetime(
                2026,
                1,
                5,
                6,
                0,
                tzinfo=timezone.utc,
            ),
            tick_minutes=1,
            live_tick_seconds=0,
            seed=args.seed,
        )

        print(
            "================================================"
        )
        print(
            "AquaSense AI DEMO MODE"
        )
        print(
            "================================================"
        )

        print(
            f"Facility : {args.facility}"
        )

        print(
            f"Fault    : {args.fault}"
        )

        print(
            f"Severity : {args.severity}"
        )

        print(
            f"Duration : {args.duration} minutes"
        )

        print(
            "================================================"
        )

        results = engine.run_demo(
            ticks=args.ticks,
            fault_type=args.fault,
            fault_duration_minutes=args.duration,
            severity=args.severity,
        )

        for result in results:

            active_faults = (
                engine.fault_injector
                .get_active_faults(
                    result.timestamp
                )
            )

            print(
                f"{result.timestamp.isoformat()} "
                f"occupancy="
                f"{sum(result.occupancy_by_zone.values())} "
                f"readings="
                f"{len(result.readings)} "
                f"active_faults="
                f"{len(active_faults)}"
            )

        print(
            "================================================"
        )

        print(
            "Demo completed."
        )

        return

    # ========================================================
    # LIVE
    # ========================================================

    engine = SimulationEngine(
        preset_name=args.facility,
        database_path=(
            settings.database_path
        ),
        start_time=datetime(
            2026,
            1,
            5,
            6,
            0,
            tzinfo=timezone.utc,
        ),
        tick_minutes=1,
        live_tick_seconds=(
            settings.live_tick_seconds
        ),
        seed=args.seed,
    )

    results = engine.run_live(
        ticks=args.ticks
    )

    for result in results:

        print(
            f"{result.timestamp.isoformat()} "
            f"occupancy="
            f"{sum(result.occupancy_by_zone.values())} "
            f"readings="
            f"{len(result.readings)}"
        )


# ============================================================
# MODULE ENTRY POINT
