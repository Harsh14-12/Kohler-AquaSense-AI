def _build_cli_parser() -> argparse.ArgumentParser:
    """Build command-line interface."""

    parser = argparse.ArgumentParser(
        description=(
            "AquaSense AI Phase 1 simulator"
        )
    )

    subparsers = (
        parser.add_subparsers(
            dest="command",
            required=True,
        )
    )

    # --------------------------------------------------------
    # HISTORICAL
    # --------------------------------------------------------

    historical = subparsers.add_parser(
        "historical",
        help="Generate historical telemetry",
    )

    historical.add_argument(
        "--days",
        type=int,
        default=7,
    )

    historical.add_argument(
        "--seed",
        type=int,
        default=42,
    )

    # --------------------------------------------------------
    # LIVE
    # --------------------------------------------------------

    live = subparsers.add_parser(
        "live",
        help="Run live telemetry simulation",
    )

    live.add_argument(
        "--facility",
        choices=available_presets(),
        default="airport",
    )

    live.add_argument(
        "--ticks",
        type=int,
        default=5,
    )

    live.add_argument(
        "--seed",
        type=int,
        default=42,
    )

    # --------------------------------------------------------
    # DEMO
    # --------------------------------------------------------

    demo = subparsers.add_parser(
        "demo",
        help="Run AquaSense demonstration mode",
    )

    demo.add_argument(
        "--facility",
        choices=available_presets(),
        default="airport",
    )

    demo.add_argument(
        "--ticks",
        type=int,
        default=15,
    )

    demo.add_argument(
        "--fault",
        choices=[
            "continuous_leak",
            "ghost_flush",
            "sensor_dropout",
            "occupancy_spike",
            "abnormal_flow",
        ],
        default="continuous_leak",
    )

    demo.add_argument(
        "--duration",
        type=int,
        default=15,
    )

    demo.add_argument(
        "--severity",
        choices=[
            "low",
            "medium",
            "high",
        ],
        default="high",
    )

    demo.add_argument(
        "--seed",
        type=int,
        default=42,
    )

    return parser


